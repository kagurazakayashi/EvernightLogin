type pendingForeignKey struct {
	refTable string
	clause   string
}

type translator struct {
	model     *schemaModel
	created   map[string]bool
	renamed   map[string]string
	pendingFK []pendingForeignKey
	extra     int
}

func (t *translator) pendingFKNames() []string {
	names := make([]string, 0, len(t.pendingFK))
	for _, item := range t.pendingFK {
		names = append(names, item.refTable)
	}
	return names
}

func (t *translator) translateMigration(statements []string) ([]string, error) {
	output := make([]string, 0, len(statements)+4)
	for _, statement := range statements {
		translated, err := t.translateStatement(statement)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", snippet(statement), err)
		}
		output = append(output, translated...)
	}
	return output, nil
}

func (t *translator) translateStatement(statement string) ([]string, error) {
	statement = strings.TrimSpace(statement)
	if statement == "" {
		return nil, nil
	}
	switch leadingKeyword(statement) {
	case "CREATE TABLE":
		table := t.model.creation[tableNameFromCreate(statement)]
		if table == nil {
			return nil, fmt.Errorf("CREATE TABLE 的表不在模型中: %s", snippet(statement))
		}
		text, extras, err := t.emitCreateTable(table)
		if err != nil {
			return nil, err
		}
		createdName := table.CreationName
		if createdName == "" {
			createdName = table.Name
		}
		t.created[createdName] = true
		output := []string{text}
		// 父表刚创建，补上等待它的外键。
		remaining := t.pendingFK[:0]
		for _, item := range t.pendingFK {
			if item.refTable == table.Name {
				output = append(output, item.clause)
				continue
			}
			remaining = append(remaining, item)
		}
		t.pendingFK = remaining
		output = append(output, extras...)
		return output, nil
	case "CREATE INDEX", "CREATE UNIQUE INDEX":
		text, err := t.emitCreateIndex(statement)
		if err != nil {
			return nil, err
		}
		return []string{text}, nil
	case "CREATE TRIGGER":
		text, err := translateTrigger(statement)
		if err != nil {
			return nil, err
		}
		return text, nil
	case "ALTER TABLE":
		return t.emitAlterTable(statement)
	case "DROP TABLE":
		name := dropTableName(statement)
		if !t.created[name] {
			return nil, fmt.Errorf("DROP TABLE 的表 %s 未在已翻译迁移中创建", name)
		}
		// PostgreSQL 不允许删除仍被外键引用的表；在翻译期静态失败，避免运行到一半。
		for liveName, liveTable := range t.model.creation {
			if !t.created[liveName] || liveName == name {
				continue
			}
			for _, column := range liveTable.Columns {
				if column.Ref != nil && t.model.resolveName(column.Ref.Table) == name {
					return nil, fmt.Errorf("表 %s 仍被 %s.%s 外键引用，不能 DROP TABLE %s",
						name, liveName, column.Name, name)
				}
			}
			for _, fk := range liveTable.TableFKs {
				if t.model.resolveName(fk.RefTable) == name {
					return nil, fmt.Errorf("表 %s 仍被 %s 外键引用，不能 DROP TABLE %s",
						name, liveName, name)
				}
			}
		}
		delete(t.created, name)
		return []string{`DROP TABLE "` + name + `"`}, nil
	case "INSERT INTO":
		return []string{normalizeInsert(statement)}, nil
	case "INSERT OR IGNORE INTO":
		return []string{convertInsertOrIgnore(statement)}, nil
	default:
		return nil, fmt.Errorf("不支持的语句类型: %s", snippet(statement))
	}
}

func normalizeInsert(statement string) string {
	return statement
}

// convertInsertOrIgnore 把 SQLite 的 INSERT OR IGNORE 翻译为 PostgreSQL
// INSERT ... ON CONFLICT DO NOTHING（只忽略唯一性/排他冲突，与仓储幂等写入的
// 可观测结果一致；CHECK/NOT NULL 等数据错误仍然报错）。
func convertInsertOrIgnore(statement string) string {
	trimmed := strings.TrimSpace(statement)
	upper := strings.ToUpper(trimmed)
	index := strings.Index(upper, "INSERT OR IGNORE INTO")
	if index < 0 {
		return statement
	}
	body := trimmed[index+len("INSERT OR IGNORE"):]
	body = strings.TrimSpace(body)
	return body + " ON CONFLICT DO NOTHING"
}

func tableNameFromCreate(statement string) string {
	trimmed := strings.TrimSpace(statement)
	rest := strings.TrimSpace(trimmed[len("CREATE TABLE"):])
	name, _ := readIdentifier(rest)
	return name
}

func (t *translator) emitCreateTable(table *tableInfo) (string, []string, error) {
	lines := make([]string, 0, len(table.Columns)+len(table.TableUniques)+len(table.TableChecks)+len(table.TableFKs)+4)
	var extras []string
	if table.Rowid {
		lines = append(lines, `"`+rowidSurrogateColumn+`" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE`)
	}
	createName := table.CreationName
	if createName == "" {
		createName = table.Name
	}
	// 主键列可能超过 btree 索引项预算。PostgreSQL 不允许表达式主键，因此为超预算的
	// 主键列生成 STORED 生成列（md5 摘要，幂等且只可能误报冲突，不会放过重复值），
	// 主键改由摘要列组成；列原值仍完整保存。
	primaryColumns := table.TablePK
	if len(primaryColumns) == 0 {
		for _, column := range table.Columns {
			if column.PrimaryKey {
				primaryColumns = []string{column.Name}
				break
			}
		}
	}
	hashColumns := map[string]string{}
	var hashLines []string
	for _, name := range primaryColumns {
		column := table.column(name)
		if column == nil {
			return "", nil, fmt.Errorf("表 %s 的主键引用了未知列 %s", table.Name, name)
		}
		if indexColumnBytes(column) <= indexEntryLimit {
			continue
		}
		hashName := "_hash_" + name
		hashColumns[name] = hashName
		hashLines = append(hashLines, quoteIdent(hashName)+" TEXT GENERATED ALWAYS AS (md5("+
			quoteIdent(name)+")) STORED")
	}
	for _, column := range table.Columns {
		line, extra, err := t.emitColumn(table, column, hashColumns[column.Name] != "")
		if err != nil {
			return "", nil, err
		}
		lines = append(lines, line)
		extras = append(extras, extra...)
	}
	lines = append(lines, hashLines...)
	if len(primaryColumns) > 0 {
		keys := make([]string, 0, len(primaryColumns))
		for _, name := range primaryColumns {
			if hashName, ok := hashColumns[name]; ok {
				keys = append(keys, hashName)
				continue
			}
			keys = append(keys, name)
		}
		lines = append(lines, "PRIMARY KEY ("+joinQuoted(keys)+")")
	}
	for index, unique := range table.TableUniques {
		safe, err := t.indexIsSafe(table, unique, true)
		if err != nil {
			return "", nil, err
		}
		if safe {
			lines = append(lines, "UNIQUE ("+joinQuoted(unique)+")")
			continue
		}
		t.extra++
		name := fmt.Sprintf("ux_%s_uq%d", table.Name, t.extra)
		extras = append(extras, "CREATE UNIQUE INDEX "+quoteIdent(name)+" ON "+quoteIdent(createName)+
			" ("+t.indexExpressions(table, unique)+")")
		_ = index
	}
	for _, check := range table.TableChecks {
		lines = append(lines, "CHECK ("+check+")")
	}
	for _, fk := range table.TableFKs {
		if len(fk.Columns) == 0 {
			continue
		}
		clause := "FOREIGN KEY (" + joinQuoted(fk.Columns) + ") REFERENCES " +
			quoteIdent(fk.RefTable) + " (" + joinQuoted(fk.RefCols) + ")" + actionSuffix(fk.Action)
		if t.parentReady(fk.RefTable, createName) {
			if fk.Name != "" {
				clause = "CONSTRAINT " + quoteIdent(fk.Name) + " " + clause
			}
			lines = append(lines, clause)
			continue
		}
		t.queueForeignKey(fk.RefTable, "ALTER TABLE "+quoteIdent(createName)+" ADD "+clause)
	}
	return "CREATE TABLE " + quoteIdent(createName) + " (\n  " + strings.Join(lines, ",\n  ") + "\n)", extras, nil
}

func actionSuffix(action string) string {
	if strings.TrimSpace(action) == "" {
		return ""
	}
	return " " + action
}

func (t *translator) parentReady(refTable, self string) bool {
	if refTable == self {
		return true
	}
	if t.created[refTable] {
		return true
	}
	if final, ok := t.renamed[refTable]; ok && t.created[final] {
		return true
	}
	return false
}

func (t *translator) queueForeignKey(refTable, clause string) {
	t.pendingFK = append(t.pendingFK, pendingForeignKey{refTable: refTable, clause: clause})
}

func (t *translator) emitColumn(table *tableInfo, column *columnInfo, hashPrimaryKey bool) (string, []string, error) {
	var extras []string
	definition := quoteIdent(column.Name)
	if column.Identity && column.SQLiteType == "TEXT" {
		length, err := identityLength(column)
		if err != nil {
			return "", nil, fmt.Errorf("表 %s: %w", table.Name, err)
		}
		definition += " " + length
	} else {
		definition += " " + column.MappedType
	}
	if column.Identity && column.SQLiteType == "INTEGER" {
		definition += " GENERATED BY DEFAULT AS IDENTITY"
	}
	// 身份命名只影响类型长度策略，不隐含 NOT NULL：可空外键（如 applications.
	// owner_user_id ON DELETE SET NULL）必须保持可空。
	if column.NotNull || column.PrimaryKey {
		definition += " NOT NULL"
	}
	if column.Default != "" {
		definition += " DEFAULT " + column.Default
	}
	if column.PrimaryKey && !hashPrimaryKey {
		definition += " PRIMARY KEY"
	}
	if column.Unique {
		safe, err := t.indexIsSafe(table, []string{column.Name}, true)
		if err != nil {
			return "", nil, err
		}
		if safe {
			definition += " UNIQUE"
		} else {
			t.extra++
			name := fmt.Sprintf("ux_%s_uq%d", table.Name, t.extra)
			extras = append(extras, "CREATE UNIQUE INDEX "+quoteIdent(name)+" ON "+quoteIdent(table.Name)+
				" ("+t.indexExpressions(table, []string{column.Name})+")")
		}
	}
	for _, check := range column.Checks {
		definition += " CHECK (" + check + ")"
	}
	if column.Ref != nil {
		clause := "REFERENCES " + quoteIdent(column.Ref.Table) + " (" + quoteIdent(column.Ref.Column) + ")" +
			actionSuffix(column.Ref.Action)
		if t.parentReady(column.Ref.Table, table.Name) {
			definition += " " + clause
		} else {
			t.queueForeignKey(column.Ref.Table,
				"ALTER TABLE "+quoteIdent(table.Name)+" ADD FOREIGN KEY ("+quoteIdent(column.Name)+") "+clause)
		}
	}
	return definition, extras, nil
}

func (t *translator) emitAlterTable(statement string) ([]string, error) {
	body := strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(statement), ";"))
	body = strings.TrimSpace(strings.TrimPrefix(body, "ALTER TABLE"))
	tableName, rest := readIdentifier(body)
	rest = strings.TrimSpace(rest)
	upper := strings.ToUpper(rest)
	switch {
	case strings.HasPrefix(upper, "ADD COLUMN"):
		if !t.created[tableName] {
			return nil, fmt.Errorf("ALTER TABLE 的表 %s 尚未创建", tableName)
		}
		table := t.model.live[tableName]
		if table == nil {
			return nil, fmt.Errorf("ALTER TABLE 的表 %s 不在模型中", tableName)
		}
		definition := strings.TrimSpace(rest[len("ADD COLUMN"):])
		name, _ := readIdentifier(definition)
		column := table.column(name)
		if column == nil {
			return nil, fmt.Errorf("表 %s 的新增列 %s 不在模型中", tableName, name)
		}
		line, extras, err := t.emitColumn(table, column, false)
		if err != nil {
			return nil, err
		}
		output := []string{"ALTER TABLE " + quoteIdent(tableName) + " ADD COLUMN " + line}
		output = append(output, extras...)
		return output, nil
	case strings.HasPrefix(upper, "RENAME TO"):
		newName := strings.TrimSpace(rest[len("RENAME TO"):])
		newName = strings.Trim(newName, "\"`")
		delete(t.created, tableName)
		t.created[newName] = true
		t.renamed[tableName] = newName
		// 重命名的表可能正是等待补外键的父表。
		remaining := t.pendingFK[:0]
		output := []string{"ALTER TABLE " + quoteIdent(tableName) + " RENAME TO " + quoteIdent(newName)}
		for _, item := range t.pendingFK {
			if item.refTable == tableName {
				output = append(output, item.clause)
				continue
			}
			remaining = append(remaining, item)
		}
		t.pendingFK = remaining
		return output, nil
	default:
		return nil, fmt.Errorf("不支持的 ALTER TABLE 形式: %s", snippet(statement))
	}
}

// indexIsSafe 判断索引键列是否可能超过 btree 索引项上限。安全返回 true；不安全时
// 唯一索引必须改用 md5 表达式索引，主键则直接报错（无法用表达式模拟）。
func (t *translator) indexIsSafe(table *tableInfo, columns []string, unique bool) (bool, error) {
	if table == nil {
		return false, fmt.Errorf("索引引用了未知表")
	}
	safe := true
	for _, name := range columns {
		column := table.column(name)
		if column == nil {
			return false, fmt.Errorf("索引引用了表 %s 的未知列 %s", table.Name, name)
		}
		if indexColumnBytes(column) > indexEntryLimit {
			safe = false
		}
	}
	if !safe && unique {
		// 调用方负责把唯一约束改为 md5 表达式索引；仅提前返回不安全状态。
		return false, nil
	}
	return safe, nil
}

// indexColumnBytes 估算索引键列的最坏字节数；未知上界按“不安全”处理。
func indexColumnBytes(column *columnInfo) int {
	if column.MappedType == "BYTEA" {
		if column.LengthMax == 0 {
			return indexEntryLimit + 1
		}
		return column.LengthMax
	}
	if strings.HasPrefix(column.MappedType, "VARCHAR(") {
		length := 0
		fmt.Sscanf(strings.TrimSuffix(strings.TrimPrefix(column.MappedType, "VARCHAR("), `) COLLATE "C"`), "%d", &length)
		if length == 0 {
			return indexEntryLimit + 1
		}
		return length * bytesPerCharWorstCase
	}
	if strings.HasPrefix(column.MappedType, "TEXT") {
		if column.LengthMax == 0 {
			return indexEntryLimit + 1
		}
		return column.LengthMax * bytesPerCharWorstCase
	}
	return 0
}

// indexExpressions 生成索引列表达式，超过预算的键列用 md5() 摘要（唯一性不会放宽：
// md5 冲突只会造成误报冲突，不会放过真正的重复值）。
func (t *translator) indexExpressions(table *tableInfo, columns []string) string {
	expressions := make([]string, 0, len(columns))
	for _, name := range columns {
		column := table.column(name)
		if column != nil && indexColumnBytes(column) > indexEntryLimit {
			expressions = append(expressions, "md5("+quoteIdent(name)+")")
			continue
		}
		expressions = append(expressions, quoteIdent(name))
	}
	return strings.Join(expressions, ", ")
}

var createIndexPattern = regexp.MustCompile(`(?is)^CREATE\s+(UNIQUE\s+)?INDEX\s+([A-Za-z0-9_]+)\s+ON\s+([A-Za-z0-9_]+)\s*\(([^)]*(?:\([^)]*\)[^)]*)*)\)(.*)$`)

func (t *translator) emitCreateIndex(statement string) (string, error) {
	trimmed := strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(statement), ";"))
	match := createIndexPattern.FindStringSubmatch(trimmed)
	if match == nil {
		return "", fmt.Errorf("无法解析 CREATE INDEX: %s", snippet(statement))
	}
	unique := strings.TrimSpace(match[1]) != ""
	name := match[2]
	tableName := strings.Trim(match[3], "\"`")
	table := t.model.live[t.model.resolveName(tableName)]
	if table == nil {
		table = t.model.creation[tableName]
	}
	if table == nil {
		return "", fmt.Errorf("索引 %s 引用了未知表 %s", name, match[3])
	}
	parts := splitTopLevel(match[4], ',')
	expressions := make([]string, 0, len(parts))
	for _, part := range parts {
		raw := strings.TrimSpace(part)
		columnName := raw
		order := ""
		if fields := strings.Fields(raw); len(fields) >= 2 {
			columnName = fields[0]
			order = " " + strings.Join(fields[1:], " ")
		}
		column := table.column(columnName)
		if column == nil {
			// 表达式索引（如 md5(...)）原样保留；当前迁移没有此类写法。
			expressions = append(expressions, raw)
			continue
		}
		if indexColumnBytes(column) > indexEntryLimit {
			expressions = append(expressions, "md5("+quoteIdent(columnName)+")"+order)
			continue
		}
		expressions = append(expressions, quoteIdent(columnName)+order)
	}
	whereClause := strings.TrimSpace(match[5])
	suffix := ""
	if whereClause != "" {
		translated, err := translateCheckExpression(whereClause)
		if err != nil {
			return "", err
		}
		suffix = " " + translated
	}
	prefix := "CREATE INDEX "
	if unique {
		prefix = "CREATE UNIQUE INDEX "
	}
	return prefix + quoteIdent(name) + " ON " + quoteIdent(tableName) +
		" (" + strings.Join(expressions, ", ") + ")" + suffix, nil
}

// ---------------------------------------------------------------------------
// 触发器：SQLite BEGIN ... SELECT RAISE(ABORT, ...) END 翻译为 PL/pgSQL 函数 +
// CREATE TRIGGER。append-only 语义不变；WHEN 条件放进函数体（PostgreSQL 触发器
// WHEN 子句对子查询有限制，放进 IF EXISTS 更稳妥）。
// ---------------------------------------------------------------------------

var triggerPattern = regexp.MustCompile(`(?is)^CREATE\s+TRIGGER\s+([A-Za-z0-9_]+)\s+(BEFORE|AFTER)\s+(INSERT|UPDATE|DELETE)\s+ON\s+([A-Za-z0-9_]+)\s+(?:WHEN\s+(.+?)\s+)?BEGIN\s+SELECT\s+RAISE\s*\(\s*ABORT\s*,\s*'((?:[^']|'')*)'\s*\)\s*;\s*END\s*;?\s*$`)

func translateTrigger(statement string) ([]string, error) {
	trimmed := strings.TrimSpace(statement)
	match := triggerPattern.FindStringSubmatch(trimmed)
	if match == nil {
		return nil, fmt.Errorf("不支持的触发器形式: %s", snippet(statement))
	}
	name := match[1]
	timing := match[2]
	event := match[3]
	table := match[4]
	when := strings.TrimSpace(match[5])
	message := strings.ReplaceAll(match[6], "'", "''")
	functionName := name + triggerFunctionSuffix
	var body strings.Builder
	body.WriteString("CREATE FUNCTION " + quoteIdent(functionName) + "() RETURNS trigger LANGUAGE plpgsql AS $body$\nBEGIN\n")
	indent := "  "
	if when != "" {
		condition, err := translateCheckExpression(when)
		if err != nil {
			return nil, fmt.Errorf("触发器 %s 的 WHEN 条件翻译失败: %w", name, err)
		}
		body.WriteString(indent + "IF " + condition + " THEN\n")
		indent += "  "
	}
	body.WriteString(indent + "RAISE EXCEPTION '" + message + "';\n")
	if when != "" {
		body.WriteString("  END IF;\n")
	}
	body.WriteString("END;\n$body$")
	trigger := "CREATE TRIGGER " + quoteIdent(name) + " " + timing + " " + event + " ON " + quoteIdent(table) +
		" FOR EACH ROW EXECUTE FUNCTION " + quoteIdent(functionName) + "()"
	return []string{body.String(), trigger}, nil
}

