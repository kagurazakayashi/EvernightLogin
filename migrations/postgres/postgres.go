// Package postgres 把已提交的 SQLite 迁移确定性翻译为 PostgreSQL 方言迁移。
//
// 设计边界（与 migrations/mysql 对齐、但独立实现）：
//   - 只共享 internal/storage/migrate 的加载/校验/语句拆分机制；DDL 解析与生成各自
//     实现。原因：MySQL 需要提升列内联外键、模拟 partial 生成列、按 utf8mb4 字节
//     预算生成 SHA-256 列；PostgreSQL 原生支持 inline REFERENCES、partial index、
//     CHECK，但需要显式 COLLATE "C"、identity、pg 风格的 json 校验表达式和触发器
//     函数，两者没有可共用的中间表示，强行抽象反而会互相污染。
//   - 翻译是确定性的：同样的 SQLite 迁移文件必然产生同样的 PostgreSQL 语句与校验和。
//   - 不猜测：遇到无法等价翻译的 SQLite 语法立即报错，不做静默降级。
//
// 关键方言决定（详见 docs/database/postgres_adapter.md）：
//   - 时间统一 UTC 毫秒 BIGINT（不引入 timestamptz 时区歧义）；布尔 INTEGER 0/1
//     继续用 BIGINT + CHECK，不改为 boolean（仓储以整数绑定/扫描）。
//   - 所有 TEXT 列显式 COLLATE "C"（字节序、确定性比较），与 SQLite 默认 BINARY
//     语义一致；规范化用户名仍由服务层统一，数据库只按字节保证唯一性。
//   - 身份列（id / *_id）使用 VARCHAR(max(128, CHECK 上界)) COLLATE "C"：既满足
//     服务层 128 字符公开上限，也避免无界 TEXT 成为索引键；上界超过安全阈值时
//     翻译期直接失败，而不是截断或用短长度。
//   - JSON 列保持 TEXT（字节保真），CHECK(json_valid(x)) 翻译为
//     (x IS NULL OR (x)::jsonb IS NOT NULL)；非法 JSON 由 PostgreSQL 拒绝。
//   - 索引键若可能超过 btree 索引行上限（1/3 页，约 2704 字节），唯一约束/索引改用
//     md5(<列>) 函数索引（只会误报冲突，不会放过重复值）；主键出现该情况直接报错。
//   - rowid 代理列：4 张被仓储用 rowid 排序/删除的表追加
//     _rowid BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE，
//     仓储 SQL 里的裸 rowid 由 internal/storage/postgres 重写为 _rowid。
//   - SQLite 触发器（BEGIN ... SELECT RAISE(ABORT, ...) END）翻译为 PL/pgSQL 触发器
//     函数 + CREATE TRIGGER（append-only 语义保留）。
