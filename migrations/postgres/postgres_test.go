// TestTranslateAllSQLiteMigrations 是 46 个既有迁移的 PostgreSQL 版本静态验收：
// 全部可翻译、版本/描述一致、SQLite 语法不泄漏、类型/排序规则/触发器结构正确。
func TestTranslateAllSQLiteMigrations(t *testing.T) {
	source, err := migrate.LoadMigrations(migrations.SQLite)
	if err != nil {
		t.Fatalf("读取 SQLite 迁移失败: %v", err)
	}
	translated, err := Load()
	if err != nil {
		t.Fatalf("翻译 PostgreSQL 迁移失败: %v", err)
	}
	if len(translated) != 46 || len(translated) != len(source) {
		t.Fatalf("迁移数量 = %d/%d，期望 46", len(translated), len(source))
	}
	for index := range source {
		if translated[index].Version != source[index].Version {
			t.Fatalf("第 %d 条版本 = %s，期望 %s", index, translated[index].Version, source[index].Version)
		}
		if translated[index].Description != source[index].Description {
			t.Fatalf("版本 %s 描述 = %q，期望 %q", translated[index].Version,
				translated[index].Description, source[index].Description)
		}
		if translated[index].NonTransactional {
			t.Fatalf("版本 %s 不应标记 non-transactional（PostgreSQL 支持事务内 DDL）", translated[index].Version)
		}
		if translated[index].Checksum == "" || translated[index].Checksum == source[index].Checksum {
			t.Fatalf("版本 %s 需要独立的 PostgreSQL 校验和", translated[index].Version)
		}
	}

	var all strings.Builder
	for _, migration := range translated {
		for _, statement := range migration.Statements {
			all.WriteString(statement)
			all.WriteString("\n;\n")
		}
	}
	joined := all.String()

	for _, forbidden := range []string{"PRAGMA ", "json_valid(", "AUTOINCREMENT", "INSERT OR ",
		"ON CONFLICT", "RAISE(", "WITHOUT ROWID", "`",
	} {
		if strings.Contains(joined, forbidden) {
			t.Errorf("PostgreSQL 迁移仍含 SQLite/MySQL 语法 %q", forbidden)
		}
	}
	if regexp.MustCompile(`(?i)(^|[^_A-Za-z0-9])rowid([^_A-Za-z0-9]|$)`).MatchString(joined) {
		t.Error("PostgreSQL 迁移仍含裸 rowid")
	}
	if count := strings.Count(joined, "CREATE TABLE "); count != 96 {
		t.Errorf("CREATE TABLE 数量 = %d，期望 96", count)
	}
	if count := strings.Count(joined, `TEXT COLLATE "C"`); count == 0 {
		t.Error("TEXT 列缺少显式 COLLATE \"C\"")
	}
	if count := strings.Count(joined, "CREATE FUNCTION "); count != 4 {
		t.Errorf("触发器函数数量 = %d，期望 4", count)
	}
	if count := strings.Count(joined, "CREATE TRIGGER "); count != 4 {
		t.Errorf("触发器数量 = %d，期望 4", count)
	}
	if count := strings.Count(joined, `"`+rowidSurrogateColumn+`" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE`); count != 4 {
		t.Errorf("_rowid 代理列数量 = %d，期望 4", count)
	}
	if count := strings.Count(joined, "md5("); count == 0 {
		t.Error("超过索引项预算的键列未使用 md5() 函数索引")
	} else {
		t.Logf("翻译统计：CREATE TABLE=%d、TEXT COLLATE \"C\"=%d、md5() 索引=%d、触发器函数=%d",
			strings.Count(joined, "CREATE TABLE "), strings.Count(joined, `TEXT COLLATE "C"`),
			count, strings.Count(joined, "CREATE FUNCTION "))
	}
	// 部分唯一索引必须原样保留 WHERE 子句（PostgreSQL 原生支持 partial index）。
	if !strings.Contains(joined, "CREATE UNIQUE INDEX \"ux_single_root\" ON \"users\" (\"is_root\") WHERE is_root=1") {
		t.Error("partial unique index 未按 PostgreSQL 原生写法保留")
	}
	// 外键必须存在（inline 或 ALTER 提升），且父表先于引用存在。
	if !strings.Contains(joined, "REFERENCES") {
		t.Error("翻译结果缺少外键")
	}
	if _, err := migrate.NewRunner(stubBackend{}, translated); err != nil {
		t.Fatalf("翻译后的迁移集合不能被迁移执行器接受: %v", err)
	}
}

// TestTranslatedKeyDDL 抽查关键方言映射，防止后续修改静默改变安全语义。
func TestTranslatedKeyDDL(t *testing.T) {
	translated, err := Load()
	if err != nil {
		t.Fatalf("翻译失败: %v", err)
	}
	byVersion := map[string]string{}
	for _, migration := range translated {
		byVersion[migration.Version] = strings.Join(migration.Statements, "\n;\n")
	}
	users := byVersion["0001"]
	for _, want := range []string{
		`"id" VARCHAR(128) COLLATE "C" NOT NULL PRIMARY KEY`,
		`"username_normalized" VARCHAR(254) COLLATE "C" NOT NULL UNIQUE`,
		`"profile_json" TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK ((profile_json IS NULL OR (profile_json)::jsonb IS NOT NULL))`,
		`"app_id" VARCHAR(128) COLLATE "C"`,
	} {
		if !strings.Contains(users, want) {
			t.Errorf("0001 缺少预期 DDL 片段 %q", want)
		}
	}
	// 外键：列内联 REFERENCES 保留为 PostgreSQL inline 外键。
	if !strings.Contains(users, `"owner_user_id" VARCHAR(128) COLLATE "C" REFERENCES "users" ("id") ON DELETE SET NULL`) {
		t.Errorf("0001 的列内联外键翻译不正确: %s", users)
	}
	// AUTOINCREMENT 主键翻译为 identity。
	statistics := byVersion["0041"]
	if !strings.Contains(statistics, `"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY`) {
		t.Errorf("0041 的 AUTOINCREMENT 主键翻译不正确")
	}
	// 重建表 + 数据搬迁 + 重命名。
	fido := byVersion["0023"]
	for _, want := range []string{`CREATE TABLE "webauthn_credentials_v2"`,
		"INSERT INTO webauthn_credentials_v2",
		`DROP TABLE "webauthn_credentials"`,
		`ALTER TABLE "webauthn_credentials_v2" RENAME TO "webauthn_credentials"`} {
		if !strings.Contains(fido, want) {
			t.Errorf("0023 缺少预期语句 %q", want)
		}
	}
	// 触发器：append-only 语义必须保留。
	support := byVersion["0026"]
	if !strings.Contains(support, "CREATE FUNCTION \"trg_support_case_events_no_update_fn\"() RETURNS trigger LANGUAGE plpgsql") {
		t.Errorf("0026 触发器函数翻译不正确")
	}
	if !strings.Contains(support, "RAISE EXCEPTION 'support_case_events is append-only';") {
		t.Errorf("0026 触发器缺少 RAISE EXCEPTION")
	}
	auditRead := byVersion["0040"]
	if !strings.Contains(auditRead, "IF EXISTS(SELECT 1 FROM audit_maintenance_log WHERE id=NEW.id) THEN") {
		t.Errorf("0040 带 WHEN 的触发器条件翻译不正确")
	}
	// webhook url 上界 2048 字符，超过索引项预算，唯一约束必须改为 md5 函数索引。
	webhook := byVersion["0037"]
	if !strings.Contains(webhook, "md5(\"url\")") {
		t.Errorf("0037 超长 url 唯一约束未使用 md5 函数索引")
	}
}

// TestIdentityAndCheckLengths 防止身份 ID 列被映射得过短，并断言外键列与父列类型
// 完全一致（不同长度/排序规则会导致合法 ID 被拒或跨库语义分叉）。
func TestIdentityAndCheckLengths(t *testing.T) {
	source, err := migrate.LoadMigrations(migrations.SQLite)
	if err != nil {
		t.Fatalf("读取迁移失败: %v", err)
	}
	parsed := make([]parsedMigration, 0, len(source))
	for _, migration := range source {
		statements := migration.Statements
		if len(statements) == 1 {
			statements, err = splitWholeFileScript(statements[0])
			if err != nil {
				t.Fatalf("拆分 %s 失败: %v", migration.FileName, err)
			}
		}
		parsed = append(parsed, parsedMigration{source: migration, statements: statements})
	}
	model, err := buildSchema(parsed)
	if err != nil {
		t.Fatalf("构建模型失败: %v", err)
	}
	identityColumns := 0
	limitedColumns := 0
	for _, table := range model.tables {
		for _, column := range table.Columns {
			if column.SQLiteType != "TEXT" {
				continue
			}
			if column.Identity {
				identityColumns++
				length := varcharLength(column.MappedType)
				if length < identityMinLength {
					t.Errorf("表 %s 身份列 %s = %s，短于 API 上限 %d",
						table.Name, column.Name, column.MappedType, identityMinLength)
				}
				if column.LengthMax > length {
					t.Errorf("表 %s 身份列 %s = %s，短于 SQLite CHECK 上界 %d",
						table.Name, column.Name, column.MappedType, column.LengthMax)
				}
			}
			if column.LengthMax > 0 {
				limitedColumns++
				if !strings.Contains(column.MappedType, "COLLATE") {
					t.Errorf("表 %s 列 %s 缺少显式 COLLATE", table.Name, column.Name)
				}
			}
		}
	}
	t.Logf("模型统计：表 %d、身份 TEXT 列 %d、CHECK 上界列 %d", len(model.tables), identityColumns, limitedColumns)
	if identityColumns < 200 || limitedColumns < 20 {
		t.Fatalf("断言样本过少：身份列 %d、CHECK 上界列 %d", identityColumns, limitedColumns)
	}
	foreignKeys := 0
	for _, table := range model.tables {
		for _, column := range table.Columns {
			if column.Ref == nil {
				continue
			}
			parent := model.live[model.resolveName(column.Ref.Table)]
			if parent == nil {
				t.Errorf("表 %s 列 %s 外键引用未知表 %s", table.Name, column.Name, column.Ref.Table)
				continue
			}
			reference := parent.column(column.Ref.Column)
			if reference == nil {
				t.Errorf("表 %s 列 %s 外键引用未知列 %s.%s", table.Name, column.Name, column.Ref.Table, column.Ref.Column)
				continue
			}
			foreignKeys++
			if column.MappedType != reference.MappedType {
				t.Errorf("表 %s 外键列 %s(%s) 与父列 %s.%s(%s) 类型不一致",
					table.Name, column.Name, column.MappedType, column.Ref.Table, column.Ref.Column, reference.MappedType)
			}
		}
		for _, fk := range table.TableFKs {
			parent := model.live[model.resolveName(fk.RefTable)]
			if parent == nil {
				t.Errorf("表 %s 表级外键引用未知表 %s", table.Name, fk.RefTable)
				continue
			}
			for index, child := range fk.Columns {
				if index >= len(fk.RefCols) {
					continue
				}
				childColumn := table.column(child)
				reference := parent.column(fk.RefCols[index])
				if childColumn == nil || reference == nil {
					continue
				}
				foreignKeys++
				if childColumn.MappedType != reference.MappedType {
					t.Errorf("表 %s 外键列 %s(%s) 与父列 %s.%s(%s) 类型不一致",
						table.Name, child, childColumn.MappedType, fk.RefTable, fk.RefCols[index], reference.MappedType)
				}
			}
		}
	}
	t.Logf("外键类型一致性断言：%d 列", foreignKeys)
	if foreignKeys < 80 {
		t.Fatalf("外键类型断言样本过少: %d", foreignKeys)
	}
}

func varcharLength(mappedType string) int {
	if !strings.HasPrefix(mappedType, "VARCHAR(") {
		return 0
	}
	inner := strings.TrimSuffix(strings.TrimPrefix(mappedType, "VARCHAR("), `) COLLATE "C"`)
	length := 0
	fmt.Sscanf(inner, "%d", &length)
	return length
}

// TestTranslateDeterministic 确认翻译是确定性的：两次结果校验和一致。
func TestTranslateDeterministic(t *testing.T) {
	first, err := Load()
	if err != nil {
		t.Fatalf("第一次翻译失败: %v", err)
	}
	second, err := Load()
	if err != nil {
		t.Fatalf("第二次翻译失败: %v", err)
	}
	for index := range first {
		if first[index].Checksum != second[index].Checksum {
			t.Fatalf("版本 %s 两次翻译校验和不一致", first[index].Version)
		}
	}
}

