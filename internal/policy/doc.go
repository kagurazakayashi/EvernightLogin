// Package policy 实现可管理的敏感操作目录、root 策略配置与恢复默认。
//
// 本包是步骤 38 的策略配置层，不执行任何敏感操作本身（执行器在后续步骤接入）。
// 它集中登记此前分散在各模块中的临时保守策略定义，形成唯一、稳定、机器可读的
// 基线：
//   - 系统内置目录（DefaultCatalog）是只读代码基线：每个敏感操作都有稳定标识、
//     中文名称与说明、默认策略（是否敏感、认证新鲜度、所需认证强度、确认、告知）
//     以及不可被策略覆盖的基础约束（所需权限、是否 root 专属、是否必须审计）。
//   - 数据库（迁移 0018）只保存偏离默认值的覆盖行与应用声明的操作；恢复默认即
//     删除覆盖行，因此目录升级不会重写用户配置，也不会把配置当成默认值。
//   - 系统策略与「策略变更本身」只能由真实 root 身份经再次验证后修改；普通管理员
//     和应用管理员不能修改，且取消「敏感」标记不会取消基础权限、root 专属限制或
//     审计要求（这些约束不在可覆盖字段内）。
//   - 尚未实现的验证方式不会被声明为可满足：服务用显式的可用强度集合判断，要求
//     MFA/强认证但当前环境未实现时 fail-closed（MFA_REQUIRED），不降级为密码。
//
// 与既有模块临时保守定义的关系：步骤 29 起的 authn 强认证要求、步骤 31 的
// session 管理强认证门、步骤 35 的 profile 更名再次验证、步骤 36 的 emailchange
// 再次验证、步骤 34 的 onboarding 管理强认证都属于「操作级安全要求」的临时实现；
// 本包把它们登记为目录默认值（见 Catalog 中 permission/root_only/reauth 字段），
// 实际执行统一由步骤 39 接入，在那之前既有模块的 fail-closed 行为保持不变。
