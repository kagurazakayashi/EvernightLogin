// Package task 实现可靠的单实例后台任务执行器与定时调度：排队、运行、成功、
// 失败、取消请求、已取消与超时状态，SQLite 状态持久化、重启安全恢复、全状态
// 安全审计，以及日/周/月/自定义计划、触发去重、停机错过策略、尝试历史与有界
// 退避重试。
//
// 本包不提供网络接口；任务的创建、取消、查询与计划管理必须由可信的内部调用
// 边界（已验证会话、宿主显式身份、本地管理员或系统组件）调用，禁止匿名远程
// 入口。计划与任务默认要求运行前权限复验：未配置可信回调时管理类计划拒绝触发、
// 要求权限的任务拒绝执行，绝不默认放行。
//
// 生命周期与可靠性：
//
//   - Executor.Start 先执行重启恢复：数据库中遗留的 running/cancel_requested
//     任务无法确认外部副作用是否完成，统一标记为 failed（TASK_INTERRUPTED）、
//     关闭未结束的尝试历史并审计，绝不假装成功；之后才开始领取 queued 任务。
//   - 任务处理器的执行上下文会在用户取消、停机取消或墙钟超时时被取消；处理器
//     必须响应 context、使用 exec.CommandContext 等方式清理子进程，并自行保证
//     幂等或补偿。执行器不承诺外部副作用恰好执行一次。
//   - 每次尝试写入 job_attempts；可重试失败按有界指数退避回到 queued，重试沿用
//     同一任务编号。取消、墙钟超时、显式不可重试错误、未知处理器与 panic 不重试。
//   - 每一条状态变化都在同一个 SQLite 事务中写入安全审计事件；审计写入失败会
//     拒绝该状态变化（fail-closed）。任务完成/取消竞争由数据库条件更新裁决，
//     终态一旦写入就不会被晚到的取消覆盖。
//   - 停止执行器会以具体系统主体记录 cancel_requested 并取消运行上下文，等待
//     处理器在期限内退出；queued 任务保留给下次启动领取。
//
// 定时调度：
//
//   - Scheduler 按计划表达式与 IANA 时区计算触发时刻；夏令时缺口顺延到跳变后
//     首个有效瞬间，重叠时刻只取较早瞬间；每月 29～31 日在不存在的月份跳过，
//     月末使用 last。
//   - 停机错过的触发按 skip/latest/all 策略处理，all 每次 Tick 受 max_catch_up
//     限制，剩余触发在后续 Tick 继续。
//   - (schedule_id, scheduled_at_ms) 唯一键保证同一触发时刻只入队一次；重启与
//     多实例共享数据库时也不会重复触发。
//   - 暂停只停止后续触发，恢复以恢复时刻重新锚定游标（暂停期间不补跑）；删除
//     计划只停止后续触发，已入队或运行中的任务继续执行。暂停/恢复/删除要求计划
//     所有者、系统或本地管理员，并写入安全审计。
//   - Scheduler 与 Executor 都通过注入时钟计算时间，测试可用确定性时钟手动
//     Tick，不依赖真实等待。调度器本身不创建任务处理器，也不拥有数据库连接。
