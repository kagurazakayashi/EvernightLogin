// Package serverapp 是 login-server 独立进程的宿主装配层。
//
// 它把公开根包（配置加载、内置页面、HTTP Handler、监听组件、Instance 生命周期）
// 与模块内部领域服务（SQLite 存储、迁移、审计、密钥环、维护状态、账户/认证/
// 会话/注册/入域）按依赖顺序装配成一个可真实启动的 HTTP 服务；同时提供首次
// 安全初始化流程（login-server init）。
//
// 边界与不变量（与 AGENTS.md 第 7/13 节一致）：
//   - 本包只在显式命令（serve/init）中执行装配，导入本包不会打开数据库、读取
//     秘密、监听端口或创建后台协程。
//   - 所有资源由 RunServe/RunInit 的调用栈显式释放：数据库、密钥环、审计、
//     维护状态锁、访问日志文件、Instance（含监听服务）。
//   - 默认只监听 127.0.0.1（配置校验强制）；维护状态门闸同时接入 SQLite 写闸
//     与启动模式：维护中启动只提供健康检查与维护提示，不装配业务页面。
//   - 首次初始化只接受本地受控操作者与交互式/受保护 stdin 的密码，不读取命令行
//     明文密码；初始化结束后状态为 setup_verified（等待强认证），不签发会话，
//     不伪造"已完成强认证"。
//   - 未迁移的数据库默认拒绝启动；只有显式 --migrate=apply 才执行迁移。
//   - 本包不注册 OAuth2/OIDC/设备码/扫码协议端点，也不注册管理 JSON API；这些
//     仍是后续步骤的缺口，内置页面只在已装配真实服务时才注册。
