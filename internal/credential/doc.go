// Package credential 实现可复用的短期一次性凭证服务：签发、验证并原子消费、
// 取消、替换与过期清理，供注册验证、找回密码、授权确认等后续流程使用。
//
// 每条凭证固定包含用途（Purpose）、接收方/目标（Target）、过期时间、尝试上限
// 和可选应用绑定（AppID 为空表示系统范围）。用途、目标、应用与凭证 ID 一起
// 参与摘要计算，因此把凭证搬到其它用途、目标或应用后无法通过验证。
//
// 两种凭证形态：
//
//   - 高熵令牌（KindToken）：crypto/rand 生成的 256 位随机值，数据库只保存
//     SHA-256 摘要。适合邮件链接等载体；比较失败不消耗尝试次数，避免只知道
//     公开 ID 的攻击者耗尽他人凭证。
//   - 低熵验证码（KindCode）：固定长度十进制短码，数据库保存用主密钥环材料
//     派生的 HMAC-SHA256 受密钥保护摘要（key_id 记录所用密钥）。即使数据库
//     泄露，没有主密钥也无法离线穷举；错误验证码会消耗尝试次数，达到上限后
//     凭证失效。
//
// 安全边界：随机源、摘要算法、常量时间比较、原子消费与可注入时钟集中在本包；
// 不存明文凭证、不在日志输出令牌/验证码/摘要、不创建后台协程。SQLite 生产
// 存储实现在 internal/credential/sqlite；本包尚未接入 Instance、配置加载或
// 服务启动，这些接线由后续步骤完成。
package credential
