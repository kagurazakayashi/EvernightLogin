// Package secrets 实现可还原秘密（例如 TOTP 种子）的认证加密、主密钥加载与
// 密钥轮换，供账户与 MFA 等后续内部模块使用。
//
// 本包不负责密码存储：密码与恢复代码必须使用慢哈希保存，不能按可解密形式
// 存储；本包只处理确实需要还原成原文的数据。
//
// # 密码学选择
//
//   - 认证加密使用标准库 AES-256-GCM（crypto/aes + cipher.NewGCM）。没有自造
//     密码学协议、分组模式或认证标签。
//   - 每条密文使用 crypto/rand 生成的 96 位（12 字节）随机 nonce；随机源失败
//     时返回错误，绝不回退到时间、计数器或固定值。
//   - 每个密钥与用途组合的子密钥由标准库 crypto/hkdf（HKDF-SHA256）派生，
//     把用途（purpose）作为派生信息，使不同用途使用不同的实际加密密钥。
//   - 密文使用格式版本号与 key_id；用途、对象和所属范围作为关联数据（AEAD
//     additional data）参与认证，密文被搬移到其他用途、对象或范围后无法解密。
//
// # 主密钥与密钥环
//
// 主密钥材料不在配置或代码中硬编码，也不能与密文放在同一个数据库中。它由
// 受保护文件或宿主提供者以“密钥环文档”形式提供（见 Keyring 与 Provider）。
// 密钥环同时保存当前写密钥与历史读密钥：Seal 只使用当前写密钥，Open 可以使
// 用任一历史密钥，因此轮换新密钥后旧密文仍可读取。
//
// 除秘密信封外，密钥环还提供 HMAC-SHA256 受密钥保护摘要接口（Keyring.HMACDigest），
// 供一次性凭证等只需验证、不需还原明文的场景使用；摘要同样按 keyID 与用途域
// 派生，不向调用方暴露密钥材料。
//
// # 轮换与重加密
//
// 轮换通过生成新密钥环文档完成；旧密钥保留为只读历史密钥。已经用旧密钥保存
// 的数据通过 Rotator.Reencrypt 逐条重加密为当前写密钥。重加密以“单条记录原子
// 替换”为检查点，因此可以在任意时刻中断，重新运行会继续处理仍然使用旧密钥
// 的记录，不需要额外的进度表。只有在确认没有数据继续引用旧密钥后，才能通过
// Rotator.RetireKey 退役该密钥；仍有引用或无法确认引用时明确失败，不静默删除。
//
// # 尚未接入
//
// 本包是内部实现，尚未接入 Instance 启动流程、cmd/login-server、配置加载或
// 数据库仓储；这些接入分别由后续步骤完成。本包不打开数据库、不创建后台协程、
// 不使用全局单例。
