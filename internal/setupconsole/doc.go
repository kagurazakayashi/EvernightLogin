// Package setupconsole 提供 EvernightLogin 的本地维护控制台（login-setup）核心。
//
// 定位（第12轮 277–302）：类 BIOS 的全屏 CUI，可由本机终端或已建立的 SSH 终端使用，
// 不新增匿名 HTTP 管理服务。本包只负责控制台自身的状态检测、配置诊断/编辑、草稿
// 校验与原子保存、本地维护身份与排他锁；数据库初始化/root 创建/账户方案等能力归
// 后续 WS2–WS4 步骤。包内按功能分文件（terminal/screen/detect/app/configedit/...），
// 不复制领域服务实现。
//
// 安全边界：
//   - 启动不依赖完整生产 Runtime：无配置、坏配置、无数据库、数据库不可达、结构待迁移、
//     root 缺失都必须在控制台内显示并可退出/修复，不能一启动就崩溃；
//   - 状态检测只读：不执行迁移、不创建数据库、不写用户/root/审计数据；检测失败按
//     明确类别显示，不把“连接失败”误报成“空库”；
//   - 终端控制序列输出只用于界面渲染；用户数据/日志/配置值中的 ANSI 序列必须清洗，
//     不当作终端指令执行；
//   - 秘密（主密钥、SMTP 口令等）只显示状态，不显示明文，不进入日志/报告。
package setupconsole
