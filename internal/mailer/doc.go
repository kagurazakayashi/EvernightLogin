// Package mailer 提供可注入的邮件发送接口、首个 SMTP 适配、邮件模板与可靠投递
// 任务所需的领域类型。
//
// 安全与边界：
//   - 本包不提供"默认真实外发"：SMTP 适配必须显式给出服务器地址与认证配置，
//     测试默认使用 internal/mailtest 外部 EvernightMail 进程夹具；不会自行读取真实用户地址。
//   - SMTP 适配只允许显式 TLS 模式（STARTTLS / 隐式 TLS / 无 TLS 仅限回环测试），
//     证书校验不可关闭：不提供 InsecureSkipVerify 开关，测试通过 TrustedRoots
//     注入测试自签根证书完成校验。
//   - 所有头部值在写入前检查 CR/LF 与控制字符，防止邮件头注入；主题按 RFC 2047
//     编码，正文按 base64 编码并用 CRLF 行尾。
//   - 外部邮件系统不保证恰好一次送达：投递任务语义是"至少一次 + 幂等键去重"，
//     重复执行可能产生重复邮件，业务侧不得把发送成功当作唯一性凭据。
//   - 投递记录中的模板数据用 internal/secrets 加密；**主密钥轮换必须保留旧密钥**，
//     否则轮换前入队、轮换后才执行的 queued 记录会解密失败并按不可重试失败处理
//     （fail-closed，不会降级为明文或跳过发送）。
//   - 任务执行器与投递状态使用任务表 MutexKey 串行化同一投递，但**多实例投递
//     互斥/全局对账尚未实现**：多进程同时消费同一队列需要宿主的单实例约束或后续
//     步骤的分布锁；残留 sending 记录目前不做启动扫描对账。
//   - 投递查询/重试按 Caller 与可选 Authorizer 做数据范围检查，未配置授权器时只有
//     受信 system/local_admin 主体放行；幂等键只返回同归属主体的既有记录。
