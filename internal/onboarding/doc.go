// Package onboarding 实现受控邀请、邀请接受与注册审核（步骤 34）。
//
// 边界与安全不变量：
//   - 邀请由可信 Caller 创建，显式记录发起者、目标邮箱或目标用户、适用应用、允许的
//     默认角色、到期与使用次数；目标邮箱只保存 authn.NormalizeEmail 的规范化值。
//   - 接受邀请必须同时持有邀请一次性令牌并满足身份绑定：邮箱邀请要求接受账户拥有
//     同一已验证邮箱，用户邀请要求接受者就是目标用户。知道邀请 ID 不能认领已有用户。
//   - 接受时按邀请者“当前”状态与权限重新校验：邀请者失去权限、应用停用、邀请过期/
//     取消/次数用尽都会拒绝；角色赋权经 internal/delegation.Guard.CheckAssignment
//     在同一审计事务内复核，邀请不能绕过步骤 26 的转授权限制。
//   - 使用次数在审计事务内条件原子扣减，重复接受由 (invitation_id,user_id) 主键拒绝。
//   - 注册审核只处理 users.status='pending'：批准/拒绝、账户状态与可选应用成员/角色
//     变更在同一审计事务完成；申请人不能批准自己；管理强认证未接线时用户身份一律
//     拒绝（只有受信 system/local_admin 通道可按既有边界运行）。
//   - 通知通过 internal/mailer 可靠投递任务发送；发送失败不回滚邀请/审核主事务，只
//     记录可查询的通知状态与稳定错误码，不保存令牌/邮件正文。
//   - 本包不签发会话、不注册 HTTP 路由、不装配到 cmd/login-server。
