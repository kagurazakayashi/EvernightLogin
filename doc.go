// HTTPS 单向认证由 internal/tlscert 与 login.Server 提供：配置本地 TLS 证书后
// 监听地址提供 HTTPS，非回环监听在 TLS 保护下允许。支持 PEM 证书链 + 私钥、
// 可选附加 CA/中间证书与 PKCS#12/PFX 导入，加载前校验私钥匹配、证书链组织、
// 服务器认证用途与有效期；按证书 DNS SAN（含单级通配符）选择 SNI，未知 SNI
