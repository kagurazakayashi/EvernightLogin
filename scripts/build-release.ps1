# Step 89: reproducible local release build for EvernightLogin.
#
# Builds cmd/login-server, cmd/loginctl and cmd/login-backup for the requested
# GOOS/GOARCH matrix with CGO_ENABLED=0, then assembles one self-contained
# package per target plus SHA-256 checksum manifests.
#
# Only local artifacts are produced: no git write, no commit, no push, no tag,
# no remote release, no upload. The package excludes AI-only files, runtime
# databases, logs, test keys and secrets by construction (explicit copy list).
#
# Windows PowerShell 5.1 and PowerShell 7 compatible. All messages are ASCII so
# the script runs correctly on a default Windows console code page.
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\build-release.ps1
#   powershell -File scripts\build-release.ps1 -OutputDir P:\go\tmp\deploy-step89 -Version 0.1.0-dev
#
# Output layout:
#   <OutputDir>/evernight-login-<version>-<os>-<arch>.zip  (one per target)
#   <OutputDir>/SHA256SUMS.txt                             (checksums of the zips)
#   <OutputDir>/build-matrix.txt                           (per-target build status)

[CmdletBinding()]
param(
    [string]$OutputDir = "",
    [string]$Version = "0.1.0-dev",
    [string[]]$Targets = @(
        "windows/amd64",
        "windows/arm64",
        "linux/amd64",
        "linux/arm64",
        "darwin/amd64",
        "darwin/arm64"
    )
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$repo = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
if ([string]::IsNullOrWhiteSpace($OutputDir)) {
    $OutputDir = Join-Path $repo "dist\release"
}
$OutputDir = [System.IO.Path]::GetFullPath($OutputDir)
$stageRoot = Join-Path $OutputDir "_stage"

$modulePath = "github.com/kagurazakayashi/EvernightLogin"
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

function Write-Utf8File {
    param([string]$Path, [string]$Text)
    [System.IO.File]::WriteAllText($Path, $Text, $utf8NoBom)
}

function Get-GitValue {
    param([string[]]$Arguments)
    $candidates = @()
    if (Test-Path "C:\Program Files\Git\cmd\git.exe") {
        $candidates += "C:\Program Files\Git\cmd\git.exe"
    }
    $candidates += "git"
    foreach ($candidate in $candidates) {
        try {
            $output = & $candidate @Arguments 2>$null
            if ($LASTEXITCODE -eq 0) {
                return ($output | Out-String).Trim()
            }
        } catch {
            # try next candidate
        }
    }
    return ""
}

function Remove-PathIfExists {
    param([string]$Path)
    if (Test-Path -LiteralPath $Path) {
        Remove-Item -LiteralPath $Path -Recurse -Force
    }
}

# ---------- 0. Environment and source revision (read-only git) ----------

$goVersion = (& go version) | Out-String
if ($LASTEXITCODE -ne 0) { throw "go toolchain not found in PATH" }
$goVersion = $goVersion.Trim()

$commit = Get-GitValue @("rev-parse", "--short", "HEAD")
if ([string]::IsNullOrWhiteSpace($commit)) { $commit = "unknown" }
$statusText = Get-GitValue @("status", "--porcelain")
$worktreeDirty = "no"
if (-not [string]::IsNullOrWhiteSpace($statusText)) { $worktreeDirty = "yes" }
$buildTime = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")

$env:GOMAXPROCS = "2"
$env:CGO_ENABLED = "0"

# go build resolves relative package patterns against the current directory; make
# sure the script always builds the repository it lives in (also when started
# from another working directory via -File).
Set-Location -LiteralPath $repo

New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null
Remove-PathIfExists $stageRoot
New-Item -ItemType Directory -Force -Path $stageRoot | Out-Null

# ---------- 1. Dependency and license manifest (shared by all packages) ----------

$licenseRoot = Join-Path $stageRoot "licenses"
New-Item -ItemType Directory -Force -Path $licenseRoot | Out-Null
$dependenciesLines = New-Object System.Collections.Generic.List[string]
$dependenciesLines.Add("# EvernightLogin dependency manifest")
$dependenciesLines.Add("# generated by scripts/build-release.ps1; module path version [indirect] [license files]")
$dependenciesLines.Add("# note: this is the module build list (go list -m all), not a per-binary import graph;")
$dependenciesLines.Add("#       BUILDINFO.txt shows the modules actually linked into each binary.")
$dependenciesLines.Add("# main module: $modulePath ($Version, commit $commit, worktree dirty: $worktreeDirty)")

$moduleListText = (& go list -m -f "{{.Path}}|{{.Version}}|{{.Dir}}|{{if .Main}}main{{end}}|{{if .Indirect}}indirect{{end}}" all) | Out-String
if ($LASTEXITCODE -ne 0) { throw "go list -m failed" }
$moduleLines = $moduleListText -split "`n" | Where-Object { -not [string]::IsNullOrWhiteSpace($_) }
foreach ($line in $moduleLines) {
    $fields = $line.Trim() -split "\|"
    if ($fields.Count -lt 3) { continue }
    $module = $fields[0]
    $moduleVersion = $fields[1]
    $moduleDir = $fields[2]
    $flags = @()
    if ($fields.Count -ge 4 -and $fields[3] -eq "main") { $flags += "main" }
    if ($fields.Count -ge 5 -and $fields[4] -eq "indirect") { $flags += "indirect" }
    $licenseNames = @()
    if (-not [string]::IsNullOrWhiteSpace($moduleDir) -and (Test-Path -LiteralPath $moduleDir)) {
        $licenseFiles = @()
        try {
            $licenseFiles = Get-ChildItem -LiteralPath $moduleDir -File -ErrorAction SilentlyContinue |
                Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)([._-].*)?$' }
        } catch {
            $licenseFiles = @()
        }
        if (@($licenseFiles).Count -gt 0) {
            $targetDirName = $module
            if (-not [string]::IsNullOrWhiteSpace($moduleVersion)) {
                $targetDirName = $module + "@" + $moduleVersion
            }
            $targetDir = Join-Path $licenseRoot $targetDirName
            New-Item -ItemType Directory -Force -Path $targetDir | Out-Null
            foreach ($licenseFile in $licenseFiles) {
                Copy-Item -LiteralPath $licenseFile.FullName -Destination (Join-Path $targetDir $licenseFile.Name) -Force
                $licenseNames += $licenseFile.Name
            }
        }
    }
    $lineText = $module + " " + $moduleVersion
    if ($flags.Count -gt 0) { $lineText = $lineText + " [" + ($flags -join ",") + "]" }
    if ($licenseNames.Count -gt 0) {
        $lineText = $lineText + " licenses: " + ($licenseNames -join ",")
    } else {
        $lineText = $lineText + " licenses: (none found in module cache; verify upstream)"
    }
    $dependenciesLines.Add($lineText)
}
$dependenciesText = ($dependenciesLines -join "`n") + "`n"

# ---------- 2. Cross-compile matrix ----------

$ldflags = "-s -w -X $modulePath.version=$Version -X $modulePath.commit=$commit -X $modulePath.buildTime=$buildTime"
$commands = @("./cmd/login-server", "./cmd/loginctl", "./cmd/login-backup")
$matrixLines = New-Object System.Collections.Generic.List[string]
$matrixLines.Add("# EvernightLogin build matrix")
$matrixLines.Add("# version=$Version commit=$commit worktree_dirty=$worktreeDirty build_time=$buildTime")
$matrixLines.Add("# go=$goVersion CGO_ENABLED=0 GOMAXPROCS=2")
$matrixLines.Add("# format: os/arch code=built|failed | package=<zip name>")
$matrixLines.Add("")

$packages = @()
foreach ($target in $Targets) {
    $parts = $target -split "/"
    if ($parts.Count -ne 2) {
        $matrixLines.Add($target + " code=failed reason=invalid-target")
        continue
    }
    $goos = $parts[0]
    $goarch = $parts[1]
    $artifactName = "evernight-login-$Version-$goos-$goarch"
    $targetBinDir = Join-Path $stageRoot ("bin-" + $goos + "-" + $goarch)
    New-Item -ItemType Directory -Force -Path $targetBinDir | Out-Null

    $env:GOOS = $goos
    $env:GOARCH = $goarch
    $buildFailed = $false
    $failureText = ""
    foreach ($command in $commands) {
        $exeName = $command.Split("/")[-1]
        if ($goos -eq "windows") { $exeName = $exeName + ".exe" }
        $outputPath = Join-Path $targetBinDir $exeName
        & go build -trimpath -buildvcs=false -ldflags $ldflags -o $outputPath $command
        if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $outputPath)) {
            $buildFailed = $true
            $failureText = "go build " + $command + " failed (exit " + $LASTEXITCODE + ")"
            break
        }
    }

    if ($buildFailed) {
        # No empty placeholder: report the real failure and skip packaging.
        $matrixLines.Add($target + " code=failed reason=" + $failureText.Replace("|", "/"))
        Write-Warning ("build failed: " + $target + " - " + $failureText)
        Remove-PathIfExists $targetBinDir
        continue
    }

    # ---------- 3. Assemble package for this target ----------
    $packageDir = Join-Path $stageRoot $artifactName
    Remove-PathIfExists $packageDir
    New-Item -ItemType Directory -Force -Path (Join-Path $packageDir "bin") | Out-Null
    foreach ($file in Get-ChildItem -LiteralPath $targetBinDir -File) {
        Copy-Item -LiteralPath $file.FullName -Destination (Join-Path $packageDir "bin") -Force
    }

    New-Item -ItemType Directory -Force -Path (Join-Path $packageDir "config") | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $packageDir "config\proxy") | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $packageDir "deploy") | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $packageDir "docs\deployment") | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $packageDir "docs\deployment\samples") | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $packageDir "docs\licenses") | Out-Null

    Copy-Item -LiteralPath (Join-Path $repo "docs\deployment\samples\login.server.example.yaml") `
        -Destination (Join-Path $packageDir "config\login.example.yaml") -Force
    Copy-Item -LiteralPath (Join-Path $repo "docs\deployment\samples\nginx-login.conf") `
        -Destination (Join-Path $packageDir "config\proxy\nginx-login.conf") -Force
    Copy-Item -LiteralPath (Join-Path $repo "docs\deployment\samples\Caddyfile") `
        -Destination (Join-Path $packageDir "config\proxy\Caddyfile") -Force

    $deploySamples = @(
        "Dockerfile",
        "docker-compose.yml",
        "evernight-login.service",
        "winsw-evernight-login.xml",
        "install-windows-service.ps1",
        "com.example.evernight-login.plist"
    )
    foreach ($sample in $deploySamples) {
        Copy-Item -LiteralPath (Join-Path $repo ("docs\deployment\samples\" + $sample)) `
            -Destination (Join-Path $packageDir ("deploy\" + $sample)) -Force
    }

    Copy-Item -Path (Join-Path $repo "docs\deployment\*.md") -Destination (Join-Path $packageDir "docs\deployment") -Force
    # Ship the samples under docs/deployment/samples as well, so relative links in
    # the packaged deployment docs resolve inside the package (and stay valid in
    # the repository). config/ and deploy/ remain the operator-facing copies.
    Copy-Item -Path (Join-Path $repo "docs\deployment\samples\*") -Destination (Join-Path $packageDir "docs\deployment\samples") -Force
    Copy-Item -Path (Join-Path $repo "docs\licenses\*") -Destination (Join-Path $packageDir "docs\licenses") -Recurse -Force

    # Dependency license texts collected from the module cache (deps subdirectory).
    if (Test-Path -LiteralPath $licenseRoot) {
        Copy-Item -LiteralPath $licenseRoot -Destination (Join-Path $packageDir "docs\licenses\deps") -Recurse -Force
    }

    $binaryForInfo = "bin\login-server"
    if ($goos -eq "windows") { $binaryForInfo = "bin\login-server.exe" }
    $buildInfo = (& go version -m (Join-Path $packageDir $binaryForInfo)) | Out-String
    # Strip the local staging directory from the recorded binary path so the
    # manifest never exposes build-host paths (and stays comparable across hosts).
    $buildInfo = $buildInfo.Replace($packageDir + "\", "").Replace($packageDir + "/", "")
    Write-Utf8File (Join-Path $packageDir "BUILDINFO.txt") ("target: $goos/$goarch`n" +
        "go: $goVersion`n" + "ldflags: $ldflags`n`n" + "go version -m output:`n" + $buildInfo)
    Write-Utf8File (Join-Path $packageDir "DEPENDENCIES.txt") $dependenciesText

    $versionText = @(
        "EvernightLogin local release",
        "version: $Version",
        "commit: $commit",
        "worktree_dirty: $worktreeDirty",
        "build_time_utc: $buildTime",
        "target: $goos/$goarch",
        "go: $goVersion",
        "cgo: 0",
        "",
        "Package layout:",
        "  bin/            login-server, loginctl, login-backup",
        "  config/         sample YAML and reverse proxy samples (no real secrets)",
        "  deploy/         container and OS service hosting samples",
        "  docs/deployment deployment documentation",
        "  docs/licenses   third-party notices and dependency license texts",
        "",
        "Runtime boundary:",
        "  - this package contains the embeddable Go library plus three CLIs;",
        "  - login-server supports serve (real HTTP service) and init (local one-time",
        "    first-run initialization); OAuth2/OIDC protocol endpoints and the admin",
        "    JSON API are assembled but disabled by default (enable explicitly);",
        "  - loginctl provides local management/emergency commands and online",
        "    management commands that require a running service;",
        "  - built-in Web pages are optional and replaceable by the host.",
        "Deploy with your own configuration, database, keyring and TLS material, and",
        "finish acceptance checks before exposing it as a production identity service",
        "(see docs/deployment/README.md)."
    ) -join "`n"
    Write-Utf8File (Join-Path $packageDir "VERSION.txt") ($versionText + "`n")
    Write-Utf8File (Join-Path $packageDir "README.txt") ($versionText + "`n")

    # Inner checksum manifest: every packaged file except the manifest itself.
    $innerSums = New-Object System.Collections.Generic.List[string]
    $innerFiles = Get-ChildItem -LiteralPath $packageDir -File -Recurse | Sort-Object FullName
    foreach ($file in $innerFiles) {
        if ($file.Name -eq "SHA256SUMS.txt") { continue }
        $relative = $file.FullName.Substring($packageDir.Length + 1).Replace("\", "/")
        $hash = (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
        $innerSums.Add($hash + "  " + $relative)
    }
    Write-Utf8File (Join-Path $packageDir "SHA256SUMS.txt") (($innerSums -join "`n") + "`n")

    $zipPath = Join-Path $OutputDir ($artifactName + ".zip")
    if (Test-Path -LiteralPath $zipPath) { Remove-Item -LiteralPath $zipPath -Force }
    Compress-Archive -Path $packageDir -DestinationPath $zipPath -CompressionLevel Optimal
    $packages += $zipPath
    $matrixLines.Add($target + " code=built | package=" + (Split-Path -Leaf $zipPath))
    Remove-PathIfExists $packageDir
    Remove-PathIfExists $targetBinDir
}

Remove-Item Env:GOOS -ErrorAction SilentlyContinue
Remove-Item Env:GOARCH -ErrorAction SilentlyContinue

# ---------- 4. Top-level checksum manifest and build matrix ----------

$topSums = New-Object System.Collections.Generic.List[string]
foreach ($zipPath in $packages) {
    $hash = (Get-FileHash -LiteralPath $zipPath -Algorithm SHA256).Hash.ToLowerInvariant()
    $topSums.Add($hash + "  " + (Split-Path -Leaf $zipPath))
}
Write-Utf8File (Join-Path $OutputDir "SHA256SUMS.txt") (($topSums -join "`n") + "`n")
Write-Utf8File (Join-Path $OutputDir "build-matrix.txt") (($matrixLines -join "`n") + "`n")

Remove-PathIfExists $stageRoot

Write-Host ""
Write-Host "Release build finished."
Write-Host ("  output dir : " + $OutputDir)
Write-Host ("  version    : " + $Version + " (commit " + $commit + ", worktree dirty: " + $worktreeDirty + ")")
Write-Host ("  packages   : " + $packages.Count)
foreach ($zipPath in $packages) { Write-Host ("  - " + (Split-Path -Leaf $zipPath)) }
Write-Host ("  matrix     : " + (Join-Path $OutputDir "build-matrix.txt"))
Write-Host ("  checksums  : " + (Join-Path $OutputDir "SHA256SUMS.txt"))
if ($packages.Count -eq 0) { exit 1 }
exit 0
